"""Markdown summary of every saved result, for the README.

Reads ``results/<owner__name>/*.json`` and prints three tables per run:
issue type classification, duplicate search, and the paired comparison of the
two embedding models used for search (both rank the same queries, so the
bootstrap resamples queries jointly).

Usage:
    python -m triage_lens.report --out results/summary.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import numpy as np

from triage_lens.evaluate import BOOTSTRAP_SAMPLES

REPOS = ("astral-sh/uv", "pandas-dev/pandas")
CLASSIFIERS = {
    "trust_form": "Trust the issue form (baseline)",
    "tfidf_logreg": "TF-IDF + logistic regression",
    "emb_all-minilm-l6-v2": "MiniLM embeddings + LogReg",
    "emb_all-minilm-l6-v2_prose": "MiniLM embeddings (prose only) + LogReg",
    "ft_distilbert-base-uncased": "Fine-tuned DistilBERT",
    "zs_bart-large-mnli": "Zero-shot BART-MNLI",
}
SEARCH_METHODS = {
    "bm25": "BM25 (keywords)",
    "dense_exact": "Dense, exact",
    "dense_chroma": "Dense, Chroma HNSW",
    "hybrid": "Hybrid (RRF)",
}


def _pct(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.1f}%"


def _ci(ci: list[float] | None) -> str:
    return "" if not ci else f" [{100 * ci[0]:.1f}–{100 * ci[1]:.1f}]"


def _load(path: Path) -> dict[str, Any] | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def classification_table(folder: Path) -> list[str]:
    rows = [
        "| Model | Accuracy | Macro-F1 | Issues without a form: accuracy |",
        "|---|---|---|---|",
    ]
    for name, label in CLASSIFIERS.items():
        data = _load(folder / f"{name}.json")
        if data is None:
            continue
        test = data["scores"]["test"]
        no_form = test["flagging"]["combined"]["subsets"]["no_form"]
        rows.append(
            f"| {label} | {_pct(test['accuracy'])}{_ci(test.get('accuracy_ci'))} "
            f"| {test['macro_f1']:.3f} | {_pct(no_form['accuracy'])} |"
        )
    return rows


def search_files(folder: Path) -> dict[str, dict[str, Any]]:
    return {
        path.stem.removeprefix("search_"): json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(folder.glob("search_*.json"))
    }


def search_table(files: dict[str, dict[str, Any]]) -> list[str]:
    rows = [
        "| Encoder | Method | Recall@1 | Recall@5 | Recall@10 | MRR |",
        "|---|---|---|---|---|---|",
    ]
    bm25_done = False
    for encoder, data in files.items():
        for method, label in SEARCH_METHODS.items():
            r = data["methods"].get(method)
            if r is None or (method == "bm25" and bm25_done):
                continue
            bm25_done |= method == "bm25"
            shown = "–" if method == "bm25" else encoder
            rows.append(
                f"| {shown} | {label} | {_pct(r['recall@1'])} | {_pct(r['recall@5'])} "
                f"| {_pct(r['recall@10'])}{_ci(r['ci']['recall@10'])} | {r['mrr']:.3f} |"
            )
    return rows


def _found(ranks: list[int | None]) -> np.ndarray:
    return np.array([r or 0 for r in ranks])


def _recall10(found: np.ndarray) -> float:
    return float(np.mean((found > 0) & (found <= 10)))


def _mrr(found: np.ndarray) -> float:
    return float(np.mean(np.where(found > 0, 1.0 / np.maximum(found, 1), 0.0)))


def paired_encoders(
    a: dict[str, Any], b: dict[str, Any], samples: int = BOOTSTRAP_SAMPLES, seed: int = 0
) -> dict[str, dict[str, Any]]:
    """Dense-search difference a - b on the same queries, with 95% intervals."""
    if a["ranks"]["pairs"] != b["ranks"]["pairs"]:
        raise ValueError("the two runs ranked different queries")
    fa, fb = _found(a["ranks"]["dense_exact"]), _found(b["ranks"]["dense_exact"])
    rng = np.random.default_rng(seed)
    out = {}
    for name, metric in (("recall@10", _recall10), ("mrr", _mrr)):
        draws = []
        for _ in range(samples):
            idx = rng.integers(0, len(fa), len(fa))
            draws.append(metric(fa[idx]) - metric(fb[idx]))
        out[name] = {
            "diff": metric(fa) - metric(fb),
            "ci": np.percentile(draws, [2.5, 97.5]).tolist(),
        }
    return out


HEADER = [
    "# Results summary",
    "",
    "Generated by `python -m triage_lens.report` from the JSON files in this folder.",
    "Intervals are bootstrap 95% intervals.",
    "",
]


def report(results_dir: Path) -> str:
    lines: list[str] = list(HEADER)
    for repo in REPOS:
        folder = results_dir / repo.replace("/", "__")
        if not folder.exists():
            continue
        lines += [f"## {repo}", "", "### Issue type (test split)", ""]
        lines += classification_table(folder)
        files = search_files(folder)
        if files:
            lines += ["", "### Duplicate search", ""]
            lines += search_table(files)
        if len(files) == 2:
            (name_a, a), (name_b, b) = sorted(files.items(), reverse=True)
            diff = paired_encoders(a, b)
            lines += [
                "",
                f"Paired difference {name_a} − {name_b} (dense, exact): "
                f"recall@10 {100 * diff['recall@10']['diff']:+.1f} pp"
                f"{_ci([x for x in diff['recall@10']['ci']])}, "
                f"MRR {diff['mrr']['diff']:+.3f} "
                f"[{diff['mrr']['ci'][0]:+.3f}–{diff['mrr']['ci'][1]:+.3f}].",
            ]
        precision = _load(folder / "duplicate_pairs_precision.json")
        if precision:
            lines += [
                "",
                f"Ground-truth pairs: estimated precision "
                f"{_pct(precision['estimated_precision'])}{_ci(precision['ci'])} "
                f"(manual review).",
            ]
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Markdown summary of saved results.")
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--out", type=Path, help="write to this file (UTF-8) instead of stdout")
    args = parser.parse_args(argv)
    text = report(args.results)
    if args.out:
        args.out.write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
